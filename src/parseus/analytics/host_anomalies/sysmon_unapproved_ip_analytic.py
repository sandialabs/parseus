"""
Analytic that takes data as generated by Sysmon.
Looks for IP references that are not in the whitelist.
"""

from parseus.analytics.base import Analytic
from parseus.analytics.core import build_ecs_alert
from parseus.analytics.core.suppression import SuppressionWindow
from parseus.analytics.core.suppression import window_now as _window_now
from parseus.analytics.core.operator_rules import OperatorRuleMixin
from parseus.analytics.capabilities import (
    ElasticsearchSource,
    IndexQuery,
    JoblibArtifact,
    Unsupervised,
)
from parseus.analytics.host_anomalies.rules import (
    describe_allowed_windows,
    evaluate_allow_rules,
)
from parseus.analytics.host_anomalies.sysmon_helpers import (
    extract_timestamp_from_aggregation,
    nested_get,
)
from parseus.analytics.registry import register_analytic


@register_analytic(
    key="SysmonUnapprovedIpAnalytic",
    family="host_anomalies",
    replace=True,
    data_source=ElasticsearchSource(
        run=IndexQuery(
            query={"bool": {"must_not": [{"term": {"handled": True}}]}},
            return_fields=["winlog.event_data.SourceAddress", "@timestamp"],
        ),
    ),
    training=Unsupervised(),
    persistence=JoblibArtifact(),
    init_args={"known_good_ips": ["127.0.0.1"]},
    run_idx={"index_name": "winlog*"},
    out_idx={"index_name": "alerts-sysmon_unapproved_ip_analytic"},
)
class SysmonUnapprovedIpAnalytic(OperatorRuleMixin, Analytic):
    """
    Name: SysmonUnapprovedIpAnalytic

    How: Analytic that takes data generated by Sysmon. Alerts on source IPs
         that are not in the allow-list or that violate a configured IP access
         rule (e.g. seen outside an approved time window).

    When:

    Mitre-Data-Sources:
        + Network Traffic: Network Traffic Content

    Mitre-Techniques:


    Purdue-Levels:
        + level 2
    """

    _rule_arg = "ip_rules"
    _rule_state_attr = "ip_rules_"

    def __init__(
        self,
        pull_duration=60,
        known_good_ips=None,
        ip_rules=None,
        sysmon_rules=None,
        timezone="UTC",
        **kwargs,
    ):
        super().__init__(pull_duration=pull_duration, **kwargs)
        self._transform = sysmon_ip_transform
        # Scheduled runs use raw documents (no composite aggregation): a
        # composite agg would group by SourceAddress and collapse repeated events in
        # the same window into one bucket, hiding repeated alerts. The run query
        # and return fields are declared on the analytic's data_source().
        self.known_good_ips_ = known_good_ips or []
        self.ip_rules_ = ip_rules or sysmon_rules or []
        self.default_timezone_ = timezone
        self.run_results_doc = (
            "Alerts for when an IP is found that is not in whitelist or violates "
            "a configured IP access rule"
        )

    @classmethod
    def requires_fit(cls) -> bool:
        """Tell not to fit the model before predicting."""
        return False

    def _run(self, start, end, transformed_documents, state, **other_docs):
        alerts = make_alerts(
            ip_dicts=transformed_documents,
            known_good_ips=self.known_good_ips_,
            ip_rules=self.ip_rules_,
            default_timezone=self.default_timezone_,
            window=SuppressionWindow(state, self.suppression_),
            now=end,
        )
        return alerts


def make_alerts(
    ip_dicts,
    known_good_ips,
    ip_rules=None,
    default_timezone="UTC",
    window=None,
    now=None,
):
    "Use allow-list and schedule rules to return IP alerts."
    alerts = []
    known_good_ips = set(known_good_ips or [])
    for ip_dict in ip_dicts:
        ip = ip_dict["ip"]
        allowed, rule, reason = evaluate_allow_rules(
            ip,
            ip_dict["@timestamp"],
            ip_rules,
            value_keys=("ips",),
            default_timezone=default_timezone,
        )

        if allowed is True:
            continue
        if allowed is None and ip in known_good_ips:
            continue

        # Per-IP suppression window keyed on the run clock: default "0s" always
        # emits (unchanged); a configured window re-alerts a given IP at most
        # once per window.
        if window is not None and not window.should_emit(ip, now=_window_now(now)):
            continue

        if reason == "outside_allowed_window":
            rule_name = rule.get("name", "unnamed rule") if rule else "unnamed rule"
            original = (
                f"IP {ip} was seen outside approved access window for "
                f"rule '{rule_name}'. Allowed windows: {describe_allowed_windows(rule)}"
            )
            action = "IP Outside Approved Window"
            rule_fields = {"name": rule_name, "reason": reason}
        else:
            original = f"NEW IP {ip}"
            action = "NEW IP, CHECK IP"
            rule_fields = {"reason": "not_in_whitelist"}

        alerts.append(
            build_ecs_alert(
                action,
                original,
                5.0,
                category=["connection"],
                timestamp=ip_dict["@timestamp"],
                source={"ip": ip},
                rule=rule_fields,
                handled=False,
            )
        )
    return alerts


def sysmon_ip_transform(docs, **kwargs):
    """
    Takes raw Sysmon documents or legacy aggregation buckets and returns the
    dictionaries used by the analytic.
    """
    ip_dicts = []
    for doc in docs:
        if "key" in doc:
            ip = doc["key"].get("host_ip")
            timestamp = extract_timestamp_from_aggregation(doc)
        else:
            ip = nested_get(doc, "winlog.event_data.SourceAddress")
            timestamp = doc.get("@timestamp")
        if not ip:
            continue
        ip_dicts.append({"ip": ip, "@timestamp": timestamp})
    return ip_dicts


def get_docs(datastore, index_name, query):
    "gets all docuements from the datastore that match the index and query."
    response = datastore.search(index=index_name, body=query)
    documents = response["hits"]["hits"]
    documents_dict = [doc["_source"] for doc in documents]
    return documents_dict


