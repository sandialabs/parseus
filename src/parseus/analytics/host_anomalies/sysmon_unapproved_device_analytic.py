"""
Analytic that takes data as generated by Sysmon.
Looks for connected device references that are not in the whitelist.
"""

from parseus.analytics.base import Analytic
from parseus.analytics.core import build_ecs_alert
from parseus.analytics.core.suppression import SuppressionWindow
from parseus.analytics.core.suppression import window_now as _window_now
from parseus.analytics.core.operator_rules import OperatorRuleMixin
from parseus.analytics.capabilities import (
    ElasticsearchSource,
    IndexQuery,
    JoblibArtifact,
    Unsupervised,
)
from parseus.analytics.host_anomalies.rules import (
    describe_allowed_windows,
    evaluate_allow_rules,
)
from parseus.analytics.host_anomalies.sysmon_helpers import (
    extract_timestamp_from_aggregation,
    nested_get,
)
from parseus.analytics.registry import register_analytic


@register_analytic(
    key="SysmonUnapprovedDeviceAnalytic",
    family="host_anomalies",
    replace=True,
    data_source=ElasticsearchSource(
        run=IndexQuery(
            query={
                "bool": {
                    "must": [{"term": {"event.code": 6416}}],
                    "must_not": [{"term": {"handled": True}}],
                }
            },
            return_fields=["winlog.event_data.DeviceId", "@timestamp"],
        ),
    ),
    training=Unsupervised(),
    persistence=JoblibArtifact(),
    init_args={"known_good_devices": ["USB\\VID_0000&PID_0000\\FOOBAR"]},
    run_idx={"index_name": "winlog*"},
    out_idx={"index_name": "alerts-sysmon_unapproved_device_analytic"},
)
class SysmonUnapprovedDeviceAnalytic(OperatorRuleMixin, Analytic):
    """
    Name: SysmonUnapprovedDeviceAnalytic

    How: Analytic that takes data generated by Sysmon. Alerts on connected
         devices that are not in the allow-list or that violate a configured
         device access rule (e.g. seen outside an approved time window).

    When:

    Mitre-Data-Sources:
        + Network Traffic: Network Traffic Content

    Mitre-Techniques:


    Purdue-Levels:
        + level 2
    """

    _rule_arg = "device_rules"
    _rule_state_attr = "device_rules_"

    def __init__(
        self,
        pull_duration=0,
        known_good_devices=None,
        device_rules=None,
        sysmon_rules=None,
        timezone="UTC",
        **kwargs,
    ):
        super().__init__(pull_duration=pull_duration, **kwargs)
        self._transform = sysmon_device_transform
        # Scheduled runs use raw documents (no composite aggregation): a
        # composite agg would group by DeviceId and collapse repeated events in
        # the same window into one bucket, hiding repeated alerts. The run query
        # and return fields are declared on the analytic's data_source().
        self.known_good_devices_ = known_good_devices or []
        self.device_rules_ = device_rules or sysmon_rules or []
        self.default_timezone_ = timezone

    @classmethod
    def requires_fit(cls) -> bool:
        """Tell not to fit the model before predicting."""
        return False

    def _run(self, start, end, transformed_documents, state, **other_docs):
        alerts = make_alerts(
            known_good_devices=self.known_good_devices_,
            device_dicts=transformed_documents,
            device_rules=self.device_rules_,
            default_timezone=self.default_timezone_,
            window=SuppressionWindow(state, self.suppression_),
            now=end,
        )
        return alerts


def make_alerts(
    known_good_devices,
    device_dicts,
    device_rules=None,
    default_timezone="UTC",
    window=None,
    now=None,
):
    "Use allow-list and schedule rules to return device alerts."
    alerts = []
    known_good_devices = set(known_good_devices or [])
    for device_dict in device_dicts:
        device_id = device_dict["DeviceId"]
        allowed, rule, reason = evaluate_allow_rules(
            device_id,
            device_dict["@timestamp"],
            device_rules,
            value_keys=("devices", "device_ids"),
            default_timezone=default_timezone,
        )

        if allowed is True:
            continue
        if allowed is None and device_id in known_good_devices:
            continue

        # Per-device suppression window keyed on the run clock: with the default
        # "0s" this always emits (unchanged behaviour); a configured window
        # re-alerts a given device at most once per window.
        if window is not None and not window.should_emit(device_id, now=_window_now(now)):
            continue

        if reason == "outside_allowed_window":
            rule_name = rule.get("name", "unnamed rule") if rule else "unnamed rule"
            original = (
                f"Device {device_id} was seen outside approved access window for "
                f"rule '{rule_name}'. Allowed windows: {describe_allowed_windows(rule)}"
            )
            action = "Device Outside Approved Window"
            rule_fields = {"name": rule_name, "reason": reason}
        else:
            original = f"NEW Device {device_id}"
            action = "New Device"
            rule_fields = {"reason": "not_in_whitelist"}

        alerts.append(
            build_ecs_alert(
                action,
                original,
                5.0,
                category=["host"],
                timestamp=device_dict["@timestamp"],
                device={"id": device_id},
                rule=rule_fields,
                handled=False,
            )
        )
    return alerts


def sysmon_device_transform(docs, **kwargs):
    """
    Takes raw Sysmon documents or legacy aggregation buckets and returns the
    dictionaries used by the analytic.
    """
    device_dicts = []
    for doc in docs:
        if "key" in doc:
            device_id = doc["key"].get("DeviceId")
            timestamp = extract_timestamp_from_aggregation(doc)
        else:
            device_id = nested_get(doc, "winlog.event_data.DeviceId")
            timestamp = doc.get("@timestamp")
        if not device_id:
            continue
        device_dicts.append({"DeviceId": device_id, "@timestamp": timestamp})
    return device_dicts


def get_docs(datastore, index_name, query):
    "gets all docuements from the datastore that match the index and query."
    response = datastore.search(index=index_name, body=query)
    documents = response["hits"]["hits"]
    documents_dict = [doc["_source"] for doc in documents]
    return documents_dict


