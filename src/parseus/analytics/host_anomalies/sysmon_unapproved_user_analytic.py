"""
Analytic that takes data as generated by Sysmon.
Looks for User references that are not in the whitelist.
"""

from parseus.analytics.base import Analytic
from parseus.analytics.core import build_ecs_alert
from parseus.analytics.core.suppression import SuppressionWindow
from parseus.analytics.core.suppression import window_now as _window_now
from parseus.analytics.core.operator_rules import OperatorRuleMixin
from parseus.analytics.capabilities import (
    ElasticsearchSource,
    IndexQuery,
    JoblibArtifact,
    Unsupervised,
)
from parseus.analytics.host_anomalies.rules import (
    describe_allowed_windows,
    evaluate_allow_rules,
)
from parseus.analytics.host_anomalies.sysmon_helpers import (
    extract_timestamp_from_aggregation,
    nested_get,
)
from parseus.analytics.registry import register_analytic


@register_analytic(
    key="SysmonUnapprovedUserAnalytic",
    family="host_anomalies",
    replace=True,
    data_source=ElasticsearchSource(
        run=IndexQuery(
            query={"bool": {"must_not": [{"term": {"handled": True}}]}},
            return_fields=["winlog.event_data.TargetUserName", "@timestamp"],
        ),
    ),
    training=Unsupervised(),
    persistence=JoblibArtifact(),
    init_args={"known_good_users": ["LOCAL SERVICE"]},
    run_idx={"index_name": "winlog*"},
    out_idx={"index_name": "alerts-sysmon_unapproved_user_analytic"},
)
class SysmonUnapprovedUserAnalytic(OperatorRuleMixin, Analytic):
    """
    Name: SysmonUnapprovedUserAnalytic

    How: Analytic that takes data generated by Sysmon. Alerts on users that are
         not in the allow-list or that violate a configured user access rule
         (e.g. logged in outside an approved time window).

    When:

    Mitre-Data-Sources:
        + Host logs: Host log Content

    Mitre-Techniques:


    Purdue-Levels:
        + level 2 and 3
    """

    _rule_arg = "user_rules"
    _rule_state_attr = "user_rules_"

    def __init__(
        self,
        pull_duration=60,
        known_good_users=None,
        user_rules=None,
        sysmon_rules=None,
        timezone="UTC",
        **kwargs,
    ):
        super().__init__(pull_duration=pull_duration, **kwargs)
        self._transform = sysmon_user_transform
        # Scheduled runs use raw documents (no composite aggregation): a
        # composite agg would group by TargetUserName and collapse repeated
        # events in the same window into one bucket, hiding repeated alerts. The
        # run query and return fields are declared on the analytic's
        # data_source().
        self.known_good_users_ = known_good_users or []
        self.user_rules_ = user_rules or sysmon_rules or []
        self.default_timezone_ = timezone
        self.run_results_doc = (
            "Alerts for when a user is found that is not in whitelist or violates "
            "a configured user access rule"
        )

    @classmethod
    def requires_fit(cls) -> bool:
        """Tell not to fit the model before predicting."""
        return False

    def _run(self, start, end, transformed_documents, state, **other_docs):
        alerts = make_alerts(
            user_dicts=transformed_documents,
            known_good_users=self.known_good_users_,
            user_rules=self.user_rules_,
            default_timezone=self.default_timezone_,
            window=SuppressionWindow(state, self.suppression_),
            now=end,
        )
        return alerts


def make_alerts(
    user_dicts,
    known_good_users,
    user_rules=None,
    default_timezone="UTC",
    window=None,
    now=None,
):
    "Use allow-list and schedule rules to return user alerts."
    alerts = []
    known_good_users = set(known_good_users or [])
    for user_dict in user_dicts:
        user = user_dict["user"]
        allowed, rule, reason = evaluate_allow_rules(
            user,
            user_dict["@timestamp"],
            user_rules,
            value_keys=("users",),
            default_timezone=default_timezone,
        )

        if allowed is True:
            continue
        if allowed is None and user in known_good_users:
            continue

        # Per-user suppression window keyed on the run clock: default "0s" always
        # emits (unchanged); a configured window re-alerts a given user at most
        # once per window (e.g. "24h" = one login alert per user per day).
        if window is not None and not window.should_emit(user, now=_window_now(now)):
            continue

        if reason == "outside_allowed_window":
            rule_name = rule.get("name", "unnamed rule") if rule else "unnamed rule"
            original = (
                f"User {user} logged in outside approved access window for "
                f"rule '{rule_name}'. Allowed windows: {describe_allowed_windows(rule)}"
            )
            action = "User Outside Approved Window"
            rule_fields = {"name": rule_name, "reason": reason}
        else:
            original = f"NEW User {user}"
            action = "NEW User"
            rule_fields = {"reason": "not_in_whitelist"}

        alerts.append(
            build_ecs_alert(
                action,
                original,
                5.0,
                category=["host"],
                timestamp=user_dict["@timestamp"],
                user={"name": user},
                rule=rule_fields,
                handled=False,
            )
        )
    return alerts


def sysmon_user_transform(docs, **kwargs):
    """
    Takes raw Sysmon documents or legacy aggregation buckets and returns the
    dictionaries used by the analytic.
    """
    user_dicts = []
    for doc in docs:
        if "key" in doc:
            user = doc["key"].get("user_name")
            timestamp = extract_timestamp_from_aggregation(doc)
        else:
            user = nested_get(doc, "winlog.event_data.TargetUserName")
            timestamp = doc.get("@timestamp")
        if not user:
            continue
        user_dicts.append({"user": user, "@timestamp": timestamp})
    return user_dicts


def get_docs(datastore, index_name, query):
    "gets all docuements from the datastore that match the index and query."
    response = datastore.search(index=index_name, body=query)
    documents = response["hits"]["hits"]
    documents_dict = [doc["_source"] for doc in documents]
    return documents_dict


